############################################################
# Immune Deconvolution Analysis
# Description:
#   This script performs immune cell deconvolution using
#   multiple methods (ESTIMATE, quanTIseq, TIMER, CIBERSORT,
#   and ssGSEA with TAM signatures) on RNA-seq TPM data.
#
# Usage:
#   1. Update `data_tpm` and file paths accordingly.
#   2. Run the script in R.
############################################################

# -------------------------
# Load libraries
# -------------------------
library(immunedeconv)
library(ggplot2)
library(reshape2)
library(ggpubr)
library(dplyr)
library(data.table)

# -------------------------
# Input TPM expression matrix
# -------------------------
# Replace with your TPM matrix (genes x samples)
data_tpm <- "data/tpm_matrix_pILC.txt"   # Example path
gex <- read.delim(data_tpm, row.names = 1, stringsAsFactors = FALSE)

# -------------------------
# 1. ESTIMATE Deconvolution
# -------------------------
purity <- immunedeconv::deconvolute_estimate(gex)
write.csv(purity, "results/deconvolute_estimate_pILC.csv", quote = FALSE)

# -------------------------
# Whisker Plot: ILC vs pILC
# -------------------------
# Provide file paths for precomputed results
ilc_file  <- "results/deconvolute_estimate_ILC.csv"
pilc_file <- "results/deconvolute_estimate_pILC.csv"

# Read and transpose
ilc  <- read.csv(ilc_file,  row.names = 1, check.names = FALSE)
pilc <- read.csv(pilc_file, row.names = 1, check.names = FALSE)

ilc_t <- as.data.frame(t(ilc));  ilc_t$Group  <- "ILC"
pilc_t <- as.data.frame(t(pilc)); pilc_t$Group <- "pILC"

# Combine and reshape
combined <- rbind(ilc_t, pilc_t)
combined$Group <- factor(combined$Group, levels = c("ILC", "pILC"))
long_df <- melt(combined, id.vars = "Group", variable.name = "ScoreType", value.name = "Score")

# Generate whisker plots per score
plot_list <- list()
score_types <- unique(long_df$ScoreType)

for (score in score_types) {
  score_data <- subset(long_df, ScoreType == score)
  y_max <- max(score_data$Score, na.rm = TRUE)

  p <- ggplot(score_data, aes(x = Group, y = Score, fill = Group)) +
    geom_boxplot(outlier.shape = NA, width = 0.6) +
    geom_jitter(width = 0.1, alpha = 0.7, size = 2) +
    scale_fill_manual(values = c("ILC" = "forestgreen", "pILC" = "purple")) +
    labs(title = score, y = "Score", x = "") +
    stat_compare_means(
      comparisons = list(c("ILC", "pILC")),
      method = "t.test", label = "p.signif",
      bracket.size = 0.8, tip.length = 0.02, size = 5,
      step.increase = 0.1
    ) +
    coord_cartesian(ylim = c(NA, y_max * 1.1)) +
    theme_minimal(base_size = 14) +
    theme(
      panel.grid = element_blank(),
      axis.line = element_line(color = "black"),
      plot.margin = margin(t = 50, r = 10, b = 10, l = 10),
      legend.position = "none"
    )

  plot_list[[score]] <- p
}

final_plot <- ggarrange(plotlist = plot_list, ncol = length(score_types), nrow = 1)
ggsave("results/estim_scores_plot.png", plot = final_plot, width = 12, height = 5, dpi = 300)
ggsave("results/estim_scores_plot.pdf", plot = final_plot, width = 12, height = 5)

# -------------------------
# 2. quanTIseq Deconvolution
# -------------------------
quantiseq_result <- immunedeconv::deconvolute(gex, method = "quantiseq")
write.csv(quantiseq_result, "results/quantiseq_deconvolute_pILC.csv", quote = FALSE, row.names = FALSE)

# -------------------------
# 3. TIMER Deconvolution
# -------------------------
indications <- rep("BRCA", ncol(gex))
timer_result <- immunedeconv::deconvolute(gex, method = "timer", indications = indications)
write.csv(timer_result, "results/timer_deconvolute_pILC.csv", quote = FALSE, row.names = FALSE)

# -------------------------
# 4. CIBERSORT Deconvolution
# -------------------------
set_cibersort_binary("bin/CIBERSORT.R")         # <- update path
set_cibersort_matrix("data/LM22.txt")           # <- update path
cibersort_result <- immunedeconv::deconvolute(gex, method = "cibersort")
write.csv(cibersort_result, "results/cibersort_deconvolute_pILC.csv", quote = FALSE, row.names = FALSE)

# -------------------------
# 5. ssGSEA TAM Signature Deconvolution
# -------------------------
# tams.gmt file was generated by Chelsea
ma_sigs <- parse_gmt("data/tams.gmt")
gex_dt <- fread(data_tpm, data.table = FALSE)
row.names(gex_dt) <- gex_dt[, 1]; gex_dt <- gex_dt[, -1, drop = FALSE]

res <- deconvolute_consensus_tme_custom(as.matrix(gex_dt), ma_sigs, stat_method = 'ssgsea')
write.csv(res, "results/deconvolute_tams_pILC.csv", quote = FALSE)
